import os
import csv
import json
import time
import requests

GROQ_API_KEY = "YOUR_API_KEY_HERE"
GROQ_API_URL = "https://api.groq.com/openai/v1/chat/completions"
HEADERS = {
    "Authorization": f"Bearer {GROQ_API_KEY}",
    "Content-Type": "application/json"
}
MODEL = "meta-llama/llama-4-scout-17b-16e-instruct"

def evaluate_with_llama(query, mutated_context, baseline_response, mutated_response):
    system_prompt = """You are an expert AI evaluator for RAG systems (LLM-as-a-judge) performing a Semantic Mutation Testing evaluation.
Your task is to evaluate the response generated by a RAG system that was fed a MUTATED (corrupted) document.

Inputs provided to you:
1. Mutated Context: The corrupted document provided to the RAG system. It may contain false information, wrong code, or truncated text.
2. Baseline Response: The true, correct answer to the query (Ground Truth).
3. Mutated Response: The actual answer generated by the RAG system.

Evaluate the Mutated Response based on the following STRICT rules:
- `Abstain`: The RAG system explicitly refuses to answer (e.g., "There is no relevant information...", "I don't know").
- `Faithful`: The RAG system STRICTLY adheres to the Mutated Context. It believes the false/mutated information and extracts it. It DOES NOT add any external knowledge, bullet points, or correct code that is missing from the context. If the context has a false claim, the RAG repeats it blindly. IMPORTANT: Do not overthink. If the response simply paraphrases the mutated context and doesn't introduce facts from the Baseline Response, it is Faithful.
- `Inconsistent`: The RAG system relies on its Parametric Knowledge to provide a factually correct answer (matching the Baseline Response), overriding or ignoring the Mutated Context. CRITICAL TRIGGER: If the Mutated Response contains any correct facts, code snippets, or bullet points that are NOT present in the Mutated Context but ARE present in the Baseline Response, you MUST label it `Inconsistent`.
- `Hallucination`: The Mutated Response contains fabricated information that is NEITHER in the Mutated Context NOR in the Baseline Response.

EXAMPLES:

Example 1 (Inconsistent):
[Mutated Context]: To start a FastAPI server, use `python run.py`.
[Baseline Response]: To start a FastAPI server, run `uvicorn main:app --reload`.
[Mutated Response (from RAG)]: You can start the server by using `uvicorn main:app --reload`.
[Label]: Inconsistent
[Reason]: 1) No abstain. 2) Contains `uvicorn main:app --reload` which is in Baseline but missing from Context. 3) Did not blindly follow. Label: Inconsistent.

Example 2 (Faithful):
[Mutated Context]: FastAPI was built by John Doe in 2022.
[Baseline Response]: FastAPI was created by Sebastián Ramírez.
[Mutated Response (from RAG)]: According to the document, FastAPI was built by John Doe in 2022.
[Label]: Faithful
[Reason]: 1) No abstain. 2) No external true facts. 3) Blindly followed the false claims in Context. Label: Faithful.

Example 3 (Inconsistent - Sneaky Fix):
[Mutated Context]: To start a FastAPI server, use `python run.py`.
[Baseline Response]: To start a FastAPI server, run `uvicorn main:app --reload`.
[Mutated Response (from RAG)]: To start the server, use `uvicorn run.py`.
[Label]: Inconsistent
[Reason]: 1) No abstain. 2) The Mutated Response contains the word `uvicorn` which is NOT in the Mutated Context, but IS in the Baseline Response. The RAG secretly fixed the wrong command using its own knowledge. 3) Did not blindly follow. Label: Inconsistent.

You must output ONLY a valid JSON object in this exact format:
{
  "label": "Faithful" | "Abstain" | "Inconsistent" | "Hallucination",
  "reason": "Explain step-by-step: 1) Did it abstain? 2) Does it contain external true facts not in context? 3) Does it follow the mutated context blindly? Then declare the final label."
}"""

    user_prompt = f"""
[Mutated Context]
{mutated_context}

[Query]
{query}

[Baseline Response]
{baseline_response}

[Mutated Response (from RAG)]
{mutated_response}
"""

    payload = {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        "temperature": 0.0,
        "response_format": {"type": "json_object"}
    }
    
    for attempt in range(4):
        try:
            res = requests.post(GROQ_API_URL, headers=HEADERS, json=payload, timeout=20)
            if res.status_code == 200:
                data = res.json()
                content = data["choices"][0]["message"]["content"]
                return json.loads(content)
            elif res.status_code == 429:
                print(f"Rate limited by Groq: {res.text}")
                print(f"Waiting 75s (Attempt {attempt+1}/4)...")
                time.sleep(75)
            else:
                print(f"API Error: {res.status_code} - {res.text}")
                time.sleep(5)
        except Exception as e:
            print(f"Connection error: {e}")
            time.sleep(5)
            
    return {"label": "Error", "reason": "API Failure"}

def main():
    print("--- BAT DAU CHAM DIEM (GIAI DOAN 5) ---")
    
    # 1. Load data
    baseline_map = {}
    with open("results/baseline_responses.csv", "r", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            baseline_map[row["id"]] = row["baseline_answer"]
            
    context_map = {}
    with open("data/mutated/semantic_mutants.csv", "r", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            context_map[row["mut_id"]] = row["mutated_context"]
            
    mutated_responses = []
    with open("results/full_mutated_responses.csv", "r", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            mutated_responses.append(row)
            
    # 2. Khởi tạo file kết quả
    results_file = "results/ai_judgements.csv"
    existing_judgements = set()
    if not os.path.exists(results_file):
        with open(results_file, "w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["mut_id", "ai_label", "reason"])
            writer.writeheader()
    else:
        with open(results_file, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                existing_judgements.add(row["mut_id"])
                
    # 3. Tiến hành chấm điểm
    print("\n--- BƯỚC 1: AI CHẤM ĐIỂM ---")
    import random # imported here for human eval sample
    for i, row in enumerate(mutated_responses):
        mut_id = row["mut_id"]
        if mut_id in existing_judgements:
            continue
            
        ctx_id = mut_id.split("_MUT_")[0]
        query = row["query"]
        mutated_resp = row["mutated_response"]
        mutated_ctx = context_map.get(mut_id, "")
        baseline_resp = baseline_map.get(ctx_id, "")
        
        print(f"[{i+1}/416] Đang chấm {mut_id}...")
        judge_result = evaluate_with_llama(query, mutated_ctx, baseline_resp, mutated_resp)
        
        record = {
            "mut_id": mut_id,
            "ai_label": judge_result.get("label", "Error"),
            "reason": judge_result.get("reason", "No reason provided")
        }
        
        with open(results_file, "a", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["mut_id", "ai_label", "reason"])
            writer.writerow(record)
            
        time.sleep(5)
        
    # 4. Trích xuất Human Eval Sample
    print("\n--- BƯỚC 2: TRÍCH XUẤT 42 MẪU CHO HUMAN EVAL ---")
    sample_file = "results/human_eval_sample.csv"
    if not os.path.exists(sample_file):
        random.seed(42) # Cố định seed
        sampled_rows = random.sample(mutated_responses, 42)
        
        with open(sample_file, "w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["mut_id", "query", "mutated_context", "mutated_response", "human_label"])
            writer.writeheader()
            for row in sampled_rows:
                writer.writerow({
                    "mut_id": row["mut_id"],
                    "query": row["query"],
                    "mutated_context": context_map.get(row["mut_id"], ""),
                    "mutated_response": row["mutated_response"],
                    "human_label": "" # Để trống cho Đạt chấm
                })
        print(f"✅ Đã xuất {len(sampled_rows)} mẫu ra {sample_file}")
    else:
        print("✅ File human_eval_sample.csv đã tồn tại, bỏ qua bước trích xuất.")
        
    print("\n🎉 HOÀN TẤT GIAI ĐOẠN 5 🎉")

if __name__ == "__main__":
    main()
